export interface AppIconArt {
  /** SVG background plate, including any definitions it needs. */
  background: string;
  /** SVG foreground, on a 100 by 100 canvas. */
  svg: string;
}

export type AppIconFactory = (uid: string, date?: Date) => AppIconArt;

function rect(fill: string): string {
  return '<rect width="100" height="100" fill="' + fill + '"/>';
}

function gradient(id: string, colours: readonly string[], radial = false): string {
  const stops = colours.map((colour, index) =>
    '<stop offset="' + index / (colours.length - 1) + '" stop-color="' + colour + '"/>',
  ).join('');
  const tag = radial ? 'radialGradient' : 'linearGradient';
  const direction = radial ? ' cx="28%" cy="95%" r="110%"' : ' x1="0" y1="0" x2="0" y2="1"';
  return '<defs><' + tag + ' id="' + id + '"' + direction + '>' + stops + '</' + tag + '></defs>';
}

function plate(uid: string, top: string, bottom: string): string {
  return gradient(uid + '-plate', [top, bottom]) + rect('url(#' + uid + '-plate)');
}

function art(background: string, svg: string): AppIconArt {
  return { background, svg };
}

function ticks(count: number, radius: number, major: number, minor: number, colour: string): string {
  return Array.from({ length: count }, (_, index) =>
    '<path d="M50 ' + (50 - radius) + 'v' + (index % 5 === 0 ? major : minor)
    + '" transform="rotate(' + index * 360 / count + ' 50 50)" stroke="' + colour
    + '" stroke-width="' + (index % 5 === 0 ? 1.3 : 0.65) + '"/>',
  ).join('');
}

function brandPath(name: keyof typeof BRAND_PATHS, colour: string, size = 64): string {
  const offset = (100 - size) / 2;
  return '<g transform="translate(' + offset + ' ' + offset + ') scale(' + size / 24 + ')">'
    + '<path d="' + BRAND_PATHS[name] + '" fill="' + colour + '" fill-rule="evenodd"/></g>';
}

/** Each subpath is a complete published shape; its coordinates remain untouched. */
function colouredSubpaths(path: string, colours: readonly string[], size: number): string {
  const paths = path.match(/[Mm][^Mm]*/g) ?? [];
  return '<g transform="translate(' + (100 - size) / 2 + ' ' + (100 - size) / 2 + ') scale(' + size / 24 + ')">'
    + paths.map((part, index) => '<path d="' + part + '" fill="' + (colours[index] ?? colours[0]) + '"/>').join('')
    + '</g>';
}

